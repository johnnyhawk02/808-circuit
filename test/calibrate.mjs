// Regenerates dsp/calibration.js from the cached circuit renders
// (run test/ref-render.mjs first):
//  * CALIBRATION: behavioural output trims [normal, accent] so each
//    behavioural voice hits the circuit model's Vpp at default knobs
//  * LEVEL: the circuit's LEVEL-pot gain at 1/4 and 1/2 rotation
//  * SAMPLE_CAL: volts per full-scale sample unit, and the circuit's
//    accent/normal ratio (the sample set has no accented hits)
//   node test/calibrate.mjs
import { writeFileSync, readFileSync } from 'node:fs';
import { Kit } from '../dsp/kit.js';
import { cases, render, VOICES, SR } from './match-lib.mjs';
import { loadRef } from './match.mjs';
import { parseWav } from '../dsp/wav.js';
import { CALIBRATION, LEVEL, SAMPLE_CAL } from '../dsp/calibration.js';

const vpp = (x) => { let lo = 0, hi = 0; for (const v of x) { if (v < lo) lo = v; if (v > hi) hi = v; } return hi - lo; };
const cal = {}, level = {}, scal = {};
for (const [id] of VOICES) {
  const cs = Object.fromEntries(cases(id).map((c) => [c.name, c]));
  const rN = vpp(loadRef(id, cs.n)), rA = vpp(loadRef(id, cs.a));
  level[id] = [vpp(loadRef(id, cs.l25)) / rN, vpp(loadRef(id, cs.l50)) / rN];
  // behavioural trims: start from trims of 1 and iterate (voices saturate)
  let t = [1, 1];
  for (let k = 0; k < 5; k++) {
    const m = (acc) => { const kit = new Kit(SR, { circuits: false }); const v = kit.voices[id]; v.trimN = t[0]; v.trimA = t[1]; return vpp(render(id, 'behavioural', cs[acc], { kit })); };
    const mN = m('n'), mA = m('a');
    t = [t[0] * rN / mN, t[1] * rA / mA];
  }
  cal[id] = t;
  // samples: the default-knob recording (all knobs at 5)
  const U = id.toUpperCase(), knobs = { bd: 2, sd: 2, cy: 2, oh: 1, lt: 1, mt: 1, ht: 1, lc: 1, mc: 1, hc: 1 }[id] ?? 0;
  const w = parseWav(readFileSync(new URL(`../cache/808/${U}/${U}${'50'.repeat(knobs)}.WAV`, import.meta.url)));
  scal[id] = [rN / vpp(w.data), rA / rN];
}
const fmt = (o) => Object.entries(o).map(([k, v]) => `  ${k}: [${v.map((x) => +x.toFixed(4)).join(', ')}],`).join('\n');
writeFileSync(new URL('../dsp/calibration.js', import.meta.url),
`// Generated by \`node test/calibrate.mjs\` from the circuit models' output.
// Behavioural output trims [normal, accent]: each behavioural voice matches
// its circuit model's Vpp at default knobs (LEVEL full, others 12 o'clock).
export const CALIBRATION = {
${fmt(cal)}
};
// LEVEL pot gain at 1/4 and 1/2 rotation, from the circuit models.
export const LEVEL = {
${fmt(level)}
};
// Sample set: [volts per full-scale unit, circuit accent/normal ratio].
export const SAMPLE_CAL = {
${fmt(scal)}
};
`);
console.log('wrote dsp/calibration.js');
