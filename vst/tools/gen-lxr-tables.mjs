// Writes src/dsp/LxrTables.h: the tables of the LXR-02 engine (elixir/lxr.js) that the FX bus and its modulation need.
// node vst/tools/gen-lxr-tables.mjs
import { writeFileSync, readFileSync } from 'fs';
const src = readFileSync(new URL('../../elixir/lxr.js', import.meta.url), 'utf8');
const lit = (name) => new RegExp(name + ' = new \\w+\\(\\[([\\s\\S]*?)\\]\\)').exec(src)[1].split(',').map((x) => x.trim()).filter(Boolean);
import * as L from '../../elixir/lxr.js';
import * as T from '../../elixir/lxr-tables.js';
import { MOD_TARGETS } from '../../elixir/lxr-ui-data.js';
const arr = (name, type, a) => `inline const ${type} ${name}[${a.length}] = {\n${Array.from(a).join(',').replace(/((?:[^,]*,){32})/g, '$1\n')}\n};\n`;
const P = T.PAR;
const mod = new Uint8Array(512); for (const p of L.MODULATABLE) mod[p] = 1;
const pars = {};
for (const k of ['FREQ_LFO1', 'AMOUNT_LFO1', 'VELO_MOD_AMT_1', 'WAVE_LFO1', 'RETRIGGER_LFO1', 'SYNC_LFO1', 'OFFSET_LFO1', 'VEL_DEST_1', 'TARGET_LFO1',
  'AUDIO_OUT1', 'FX_TYPE', 'FX_ROUTING', 'FX_DRY_WET', 'FX_DIST_TYPE', 'FX_P1', 'FX_RATIO', 'FX_WAVE', 'FX_DELAY_TYPE', 'END_OF_SOUND_PARAMETERS', 'NUM_PARAMS']) pars[k] = P[k];
let s = `// generated by tools/gen-lxr-tables.mjs from elixir/lxr.js (GPL-3.0, as that file): do not edit
#pragma once
#include <cstdint>
namespace t8::lxr {
${Object.entries(pars).map(([k, v]) => `constexpr int PAR_${k} = ${v};`).join('\n')}
${arr('SINE_TABLE', 'int16_t', T.SINE_TABLE)}
${arr('PARAMETER_ORDER', 'uint8_t', T.PARAMETER_ORDER)}
${arr('INIT_KIT', 'uint8_t', T.INIT_KIT)}
${arr('MOD_TARGET_PAR', 'uint16_t', MOD_TARGETS.map((m) => m[1]))}
${arr('MODULATABLE', 'uint8_t', mod)}
${arr('ECC83_TABLE', 'double', lit('ECC83_TABLE'))}
${arr('TABLE_1N914_D', 'double', lit('TABLE_1N914'))}
${arr('EXP2F_TAB_HI', 'uint32_t', lit('EXP2F_TAB_HI'))}
${arr('EXP2F_TAB_LO', 'uint32_t', lit('EXP2F_TAB_LO'))}
${arr('LOGF_INVC', 'double', lit('LOGF_INVC'))}
${arr('LOGF_LOGC', 'double', lit('LOGF_LOGC'))}
} // namespace t8::lxr
`;
writeFileSync(new URL('../src/dsp/LxrTables.h', import.meta.url), s);
console.log('ok', T.SINE_TABLE.length, T.PARAMETER_ORDER.length, T.INIT_KIT.length, MOD_TARGETS.length);
